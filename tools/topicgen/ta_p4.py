def spread_fig(heading, slots, h, names=None, cw=56, ch=76):
    """slots = [(編號, 位置名, x, y)]；編號 2 在凱爾特十字中橫放。names 可給每個位置的牌名。"""
    out = [title(heading)]
    later = []
    for i, (n, lab, x, y) in enumerate(slots):
        x += 40
        y += 34
        nm = names[i] if names else u""
        if heading.startswith(u"凱爾特") and n == u"2":
            later.append('<g transform="rotate(90 %g %g)">%s</g>' % (x + cw / 2.0, y + ch / 2.0,
                         R(x, y, cw, ch, RED, "none", 4, 2)))
            later.append(T(x + cw / 2.0, 330, u"紅框橫放＝2 " + lab + (u"：" + nm if nm else u""), 9.5, RED))
            continue
        out.append(R(x, y, cw, ch, GOLD, "var(--surface)", 4, 1.5))
        out.append(T(x + cw / 2.0, y + 22, n, 13, GOLD))
        out.append(T(x + cw / 2.0, y + 44, lab, 8.5, TXT))
        if nm:
            out.append(T(x + cw / 2.0, y + 62, nm, 8.5, ACC))
    return svg(*(out + later))


