def _curve(f, x0, x1, n, sx, sy):
    pts = []
    for i in range(n + 1):
        x = x0 + (x1 - x0) * i / float(n)
        pts.append("%s%.1f %.1f" % ("L" if i else "M", sx(x), sy(f(x))))
    return "".join(pts)


