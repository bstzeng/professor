def _packet():
    sx = lambda x: 40 + x * 56
    out = [title(u"波包：很多波疊加 → 局部的「粒子」，而且會擴散")]
    for t, y, col, w in ((0, 72, BLUE, 0.6), (1, 140, PURPLE, 1.0), (2, 205, RED, 1.6)):
        c = 2.5 + t * 3
        f = lambda x, c=c, w=w: math.exp(-(x - c) ** 2 / (2 * w * w)) / math.sqrt(w) * math.cos(6 * (x - c))
        out.append(P("M40 %d H600" % y, LINE, sw=0.6))
        out.append(P(_curve(f, 0, 10, 400, sx, lambda v, y=y: y - v * 32), col, sw=1.6))
        out.append(T(604, y - 30, u"t = %d" % t, 9.5, col, "end"))
    out.append(T(320, 258, u"波包中心以群速度前進（＝古典粒子速度），寬度隨時間變寬", 9.5, ACC))
    return svg(*out)


