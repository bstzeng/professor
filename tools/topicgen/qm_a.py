def _orbit_wave(n, cx, cy, r, col):
    pts = []
    for i in range(361):
        a = math.radians(i)
        rr = r + 9 * math.sin(n * a)
        pts.append("%s%.1f %.1f" % ("L" if i else "M", cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return [C(cx, cy, r, LINE, "none", 1), P("".join(pts), col, sw=2)]


