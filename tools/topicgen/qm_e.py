def _gauss(cx, y0, sig, hgt, col, x0, x1):
    pts = []
    for i in range(201):
        x = x0 + (x1 - x0) * i / 200.0
        pts.append("%s%.1f %.1f" % ("L" if i else "M", x, y0 - hgt * math.exp(-(x - cx) ** 2 / (2 * sig * sig))))
    return P("".join(pts) + "L%g %g L%g %g Z" % (x1, y0, x0, y0), col, col, 1.5, 0.22)


