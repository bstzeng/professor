def _changan():
    out = [title(u"唐代長安：棋盤一樣的里坊（示意）")]
    x0, y0, cw, ch = 140, 40, 36, 18
    for r in range(9):
        for c in range(10):
            x, y = x0 + c * cw, y0 + r * ch
            col = LINE
            fill = "var(--surface)"
            if (r in (4, 5)) and c == 2:
                col, fill = ORANGE, ORANGE
            if (r in (4, 5)) and c == 7:
                col, fill = BLUE, BLUE
            if r == 0 and c in (4, 5):
                col, fill = PURPLE, PURPLE
            out.append(R(x + 1, y + 1, cw - 2, ch - 2, col, fill, 1, 0.8, op=0.35 if fill != "var(--surface)" else None))
    out.append(T(x0 + 2.5 * cw, y0 + 5 * ch + 4, u"西市", 9.5, TXT))
    out.append(T(x0 + 7.5 * cw, y0 + 5 * ch + 4, u"東市", 9.5, TXT))
    out.append(T(x0 + 5 * cw, y0 + ch / 2 + 4, u"皇城", 9.5, TXT))
    out.append(P("M%g %g V%g" % (x0 + 5 * cw, y0 + ch, y0 + 9 * ch), GOLD, sw=3))
    out.append(T(x0 + 5 * cw + 6, y0 + 8 * ch + 2, u"朱雀大街", 9, GOLD, "start"))
    out.append(T(70, 90, u"每個坊", 9.5, ACC))
    out.append(T(70, 104, u"四面有牆", 9.5, ACC))
    out.append(T(70, 118, u"坊門定時開關", 9.5, ACC))
    out.append(T(320, 226, u"一百多個坊整齊排列；入夜擊鼓關坊門，之後在大街上走動叫「犯夜」", 9.5, ACC))
    return svg(out)


