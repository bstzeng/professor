def cld(nodes, edges, loops=(), r=None):
    """因果迴路圖：nodes = {k: (x, y, 文字, 顏色)}；edges = [(a, b, '+' 或 '−', 彎曲量)]；loops = [(x, y, 'R1' 或 'B1', 說明)]。"""
    out = []
    size = {}
    for k, (x, y, lab, col) in nodes.items():
        w, h = len(lab) * 11 + 14, 22
        size[k] = (w, h)

    def clip(k, qx, qy):
        x, y = nodes[k][0], nodes[k][1]
        w, h = size[k]
        dx, dy = qx - x, qy - y
        t = min((w / 2.0 + 4) / abs(dx) if dx else 1e9, (h / 2.0 + 4) / abs(dy) if dy else 1e9)
        return x + dx * t, y + dy * t

    for a, b, sg, bend in edges:
        x1, y1 = nodes[a][0], nodes[a][1]
        x2, y2 = nodes[b][0], nodes[b][1]
        mx, my = (x1 + x2) / 2.0, (y1 + y2) / 2.0
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy) or 1
        cx, cy = mx - dy / L * bend, my + dx / L * bend
        sx, sy = clip(a, cx, cy)
        ex, ey = clip(b, cx, cy)
        col = GREEN if sg == "+" else RED
        out.append(P("M%.1f %.1f Q%.1f %.1f %.1f %.1f" % (sx, sy, cx, cy, ex, ey), col, sw=1.5))
        ang = math.atan2(ey - cy, ex - cx)
        hd = 7
        out.append(P("M%.1f %.1f L%.1f %.1f L%.1f %.1f Z" % (ex, ey, ex - hd * math.cos(ang - 0.4), ey - hd * math.sin(ang - 0.4),
                                                          ex - hd * math.cos(ang + 0.4), ey - hd * math.sin(ang + 0.4)), col, col, 1))
        px, py = 0.25 * sx + 0.5 * cx + 0.25 * ex, 0.25 * sy + 0.5 * cy + 0.25 * ey
        nx, ny = -(ey - sy), ex - sx
        nl = math.hypot(nx, ny) or 1
        side = 1 if bend >= 0 else -1
        out.append(T(px + nx / nl * 10 * side, py + ny / nl * 10 * side + 4, sg, 12, col))
    for k, (x, y, lab, col) in nodes.items():
        w, h = size[k]
        out += [R(x - w / 2.0, y - h / 2.0, w, h, col, "var(--surface)", 11, 1.2), T(x, y + 4, lab, 10.5, col)]
    for x, y, lab, note in loops:
        col = RED if lab.startswith("R") else BLUE
        out += [P("M%g %g A13 13 0 1 1 %g %g" % (x - 9, y - 9, x - 13, y + 2), col, sw=1.3), T(x, y + 4, lab, 10, col)]
        if note:
            out.append(T(x, y + 26, note, 9, MUTED))
    return out


def mini(x, y, w, h, f, label, col=BLUE):
    pts = []
    for i in range(61):
        t = i / 60.0
        pts.append("%s%.1f %.1f" % ("L" if i else "M", x + t * w, y + h - f(t) * h))
    return [R(x - 6, y - 8, w + 12, h + 34, LINE, "var(--surface)", 6, 1), P("M%g %g V%g H%g" % (x, y, y + h, x + w), MUTED, sw=0.8),
            P("".join(pts), col, sw=2), T(x + w / 2.0, y + h + 18, label, 10, TXT)]


