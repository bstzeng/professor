def _margin_fig():
    out = [title(u"安全邊際:為估錯留下緩衝")]
    x0, x1, y = 60, 580, 100

    def sx(v):
        return x0 + (v - 40) * (x1 - x0) / 100.0

    out.append(P("M%g %g H%g" % (x0, y, x1), MUTED, sw=1.5))
    for v in range(40, 141, 20):
        out.append(P("M%g %g V%g" % (sx(v), y - 4, y + 4), MUTED, sw=1))
        out.append(T(sx(v), y + 18, u"%d" % v, 9, MUTED))
