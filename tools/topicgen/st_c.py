def _dcf_fig():
    out = [title(u"現金流折現:未來的錢,今天值多少(折現率 8%)")]
    base = 186
    for i in range(5):
        pv = 100 / (1.08 ** (i + 1))
        x = 80 + i * 100
        out.append(R(x, base - 100, 36, 100, GRAY, GRAY, 3, 1, op=0.25))
        out.append(R(x + 40, base - pv, 36, pv, GREEN, GREEN, 3, 1, op=0.7))
        out.append(T(x + 18, base - 104, u"100", 9, MUTED))
