_MARK = {0xD8: (u"SOI", u"影像開始"), 0xD9: (u"EOI", u"影像結束"),
         0xC0: (u"SOF0", u"畫格開始：寬高、色彩分量、抽樣"), 0xC4: (u"DHT", u"霍夫曼表"),
         0xDB: (u"DQT", u"量化表"), 0xDA: (u"SOS", u"掃描開始：之後就是壓縮資料"),
         0xE0: (u"APP0", u"JFIF 應用標記"), 0xE1: (u"APP1", u"常放 EXIF"), 0xFE: (u"COM", u"註解")}


def _markers(data):
    out, i = [], 0
    while i < len(data) - 1:
        if data[i] != 0xFF:
            i += 1
            continue
        m = data[i + 1]
        if m in (0xD8, 0xD9):
            out.append((i, m, 0))
            i += 2
            continue
        if m == 0xDA:
            ln = struct.unpack(">H", data[i + 2:i + 4])[0]
            out.append((i, m, ln))
            break
        if 0xD0 <= m <= 0xD7 or m == 0x01 or m == 0xFF:
            i += 2
            continue
        ln = struct.unpack(">H", data[i + 2:i + 4])[0]
        out.append((i, m, ln))
        i += 2 + ln
    return out


_MK = _markers(JPEG)
_MK_ROWS = []
for off, m, ln in _MK:
    name, desc = _MARK.get(m, (u"0x%02X" % m, u""))
    _MK_ROWS.append([u"0x%04X" % off, u"FF %02X" % m,
                     (u"%d" % ln) if ln else u"—", name, desc])
