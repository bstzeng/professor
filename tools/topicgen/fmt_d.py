def _grid(x0, y0, vals, cell=30, title_=u"", fmt=u"%d", hi=None, colorfn=None):
    out = []
    if title_:
        out.append(T(x0 + 4 * cell, y0 - 8, title_, 9.5, ACC))
    for r in range(8):
        for c in range(8):
            v = vals[r][c]
            col = colorfn(v) if colorfn else "var(--surface)"
            out.append(R(x0 + c * cell, y0 + r * cell, cell, cell, LINE, col, 0, 0.6,
                         op=(0.5 if colorfn else None)))
            if cell >= 22:
                out.append(mono(x0 + c * cell + cell / 2.0, y0 + r * cell + cell / 2.0 + 3.5,
                                fmt % v, 8 if abs(v) >= 100 else 9, TXT, "middle"))
    return out


