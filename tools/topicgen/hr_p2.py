def _hiit_hr():
    pts = [(0, 80), (2, 105), (6, 122), (10, 128)]
    for k in range(3):
        t0 = 10 + k * 7
        pts += [(t0 + 0.5, 138), (t0 + 1, 150), (t0 + 2, 162), (t0 + 3, 167), (t0 + 4, 170),
                (t0 + 4.5, 158), (t0 + 5, 146), (t0 + 6, 136), (t0 + 7, 132)]
    return [p for p in pts if p[0] <= 30]


