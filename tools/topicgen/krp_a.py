def _food_rows():
    return [[LS(LESSON[c], short(c)), REGIONS[BASIC[c][4]][0], u"、".join(f[0].split(u"（")[0] for f in DATA[c]["food"][:3])] for c in ORDER]


def _wh_rows():
    seen, rows = {}, []
    for c in ORDER:
        for w in DATA[c]["wh"]:
            key = w.split(u"（")[0]
            if key not in seen:
                seen[key] = []
                rows.append(key)
            seen[key].append(LS(LESSON[c], short(c)))
    return [[k, u"、".join(seen[k])] for k in rows]


def _name_rows():
    return [[LS(LESSON[c], nm(c)), BASIC[c][1], BASIC[c][2], DATA[c]["origin"]] for c in ORDER]


