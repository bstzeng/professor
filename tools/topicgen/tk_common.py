def SAY(lines):
    """對話範例：[(說話者, 台詞), ...]"""
    rows = u"".join(u'<div style="margin:4px 0"><b style="color:var(--text-muted)">%s：</b>%s</div>' % (a, b) for a, b in lines)
    return ("raw", u'<div style="border-left:3px solid var(--border);padding:6px 12px;margin:8px 0 14px;background:var(--surface)">%s</div>' % rows)


def DOS(good, bad):
    """可以說／避免說 對照表。"""
    return ("t", [u"✅ 可以這樣說", u"⚠️ 避免這樣說"], [[g, b] for g, b in zip(good, bad)])


