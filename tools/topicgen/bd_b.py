def _twelve_fig():
    import math
    names = [u"無明", u"行", u"識", u"名色", u"六入", u"觸", u"受", u"愛", u"取", u"有", u"生", u"老死"]
    out = [title(u"十二因緣:一條生命的因果環")]
    cx, cy, r = 320, 150, 100
    for i, n in enumerate(names):
        a = -math.pi / 2 + i * 2 * math.pi / 12
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        col = RED if n in (u"無明", u"愛", u"取") else ACC
        out.append(C(x, y, 20, col, "var(--surface)"))
        out.append(T(x, y + 4, n, 10, col))
        b = a + 2 * math.pi / 12
        x2, y2 = cx + r * math.cos(b), cy + r * math.sin(b)
        dx, dy = x2 - x, y2 - y
        d = math.hypot(dx, dy)
        out.append(A(x + dx * 22 / d, y + dy * 22 / d, x2 - dx * 24 / d, y2 - dy * 24 / d, LINE, sw=1.2, head=5))
    out.append(T(cx, cy - 4, u"順著看:", 9.5, MUTED))
    out.append(T(cx, cy + 12, u"苦如何生起", 9.5, MUTED))
    out.append(T(320, 284, u"紅色的「無明、愛、取」是傳統上特別強調的斷除關鍵", 9.5, RED))
    return svg(out), 300


