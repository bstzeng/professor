def tiyong(ti, yong):
    a, b = ELEM[ti], ELEM[yong]
    if a == b:
        return u"比和", u"吉"
    if GEN[b] == a:
        return u"用生體", u"大吉"
    if KE[a] == b:
        return u"體剋用", u"吉"
    if GEN[a] == b:
        return u"體生用", u"有耗損"
    return u"用剋體", u"凶"


