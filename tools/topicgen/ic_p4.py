def _grid(nums, heading):
    out = [title(heading)]
    per = 10
    for i, n in enumerate(nums):
        x = 16 + (i % per) * 62
        y = 36 + (i // per) * 100
        out.append(hexagram(x + 10, y, hex_lines(n), 40, 6, 4))
        out.append(T(x + 30, y + 70, u"%d" % n, 9, MUTED))
        out.append(T(x + 30, y + 86, HEX[n - 1][0], 10.5, ACC))
    return svg(*out)


def _guide_table(a, b):
    rows = []
    for n in range(a, b + 1):
        name, up, lo, mean = HEX[n - 1]
        rows.append([u"%d" % n, TRIGRAMS[up][1] + u"<br>" + TRIGRAMS[lo][1], fullname(n), mean])
    return ("t", [u"序", u"卦象", u"卦名", u"一句話卦意"], rows)


def _guide(a, b, heading, intro, highlights, extra, check):
    rows = (b - a) // 10 + 1
    return lesson(heading, intro[0],
                  [u"認識第 %d～%d 卦的卦名與卦象" % (a, b), u"掌握每一卦的核心意思", u"注意卦與卦之間的對照關係"],
                  [("p", intro[1]), ("h", u"1. 卦象一覽"), "FIG", ("h", u"2. 各卦卦意"), _guide_table(a, b),
                   ("h", u"3. 值得注意的卦")] + highlights,
                  extra, check,
                  fig=(_grid(range(a, b + 1), u"第 %d～%d 卦" % (a, b)), "0 0 640 %d" % (40 + rows * 100),
                       u"第 %d～%d 卦的卦象（依文王卦序）。" % (a, b)))


