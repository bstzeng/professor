def _dist_fig():
    periods = [(1969, 1980), (1981, 1993), (1994, 2005), (2006, 2015), (2016, 2025)]
    parts = [title(u"各時期的領域分布（依本課程的分類，單位：屆）")]
    x0, W = 120, 480
    for i, (a, b) in enumerate(periods):
        aw, cnt = DATA.stats(a, b)
        y = 44 + i * 34
        parts.append(T(x0 - 8, y + 15, u"%d–%d" % (a, b), 10, MUTED, "end"))
        x = x0
        for k, _ in DATA.FIELDS:
            v = cnt.get(k, 0)
            if not v:
                continue
            w = W * v / float(len(aw))
            parts.append(R(x, y, w, 22, FCOL[k], FCOL[k], 0, 0.5, op=0.75))
            if w > 16:
                parts.append(T(x + w / 2.0, y + 15, str(v), 9.5, "#fff"))
            x += w
        parts.append(T(x0 + W + 6, y + 15, u"%d 屆" % len(aw), 9.5, MUTED, "start"))
    lx, ly = 20, 222
    for k, nm in DATA.FIELDS:
        w = 24 + len(nm) * 10.5
        if lx + w > 630:
            lx, ly = 20, ly + 16
        parts.append(R(lx, ly - 9, 10, 10, FCOL[k], FCOL[k], 2, 0.5, op=0.75))
        parts.append(T(lx + 14, ly, nm, 9.5, TXT, "start"))
        lx += w
    return svg(*parts)


