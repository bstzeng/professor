def _micro_map(codes, lon0, lat0, lon1, lat1, cap, names=(), left=()):
    xs = [eu_xy(a, b)[0] for a in (lon0, lon1) for b in (lat0, lat1)]
    ys = [eu_xy(a, b)[1] for a in (lon0, lon1) for b in (lat0, lat1)]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    sc = (x1 - x0) / 400.0
    g = [CTX]
    for k, d in sorted(EU_PATHS.items()):
        if k in codes:
            continue
        g.append('<path d="%s" fill="%s" fill-rule="evenodd" stroke="var(--surface)" stroke-width="%.2f"/>' % (d, BASE_, 0.6 * sc))
    for t, lon, lat in names:
        cx, cy = eu_xy(lon, lat)
        g.append('<text x="%.1f" y="%.1f" font-size="%.1f" text-anchor="middle" fill="var(--text-muted)">%s</text>' % (cx, cy, 13 * sc, t))
    for c in codes:
        if c in EU_PATHS:
            g.append('<path d="%s" fill="%s" stroke="%s" stroke-width="%.2f"/>' % (EU_PATHS[c], HL_, HL_, 0.6 * sc))
        x, y = cap_xy(c)
        g.append('<circle cx="%.1f" cy="%.1f" r="%.1f" fill="none" stroke="%s" stroke-width="%.2f"/>' % (x, y, 9 * sc, HL_, 1.6 * sc))
        tx, anc = (x - 11 * sc, "end") if c in left else (x + 11 * sc, "start")
        g.append('<text x="%.1f" y="%.1f" font-size="%.1f" font-weight="bold" text-anchor="%s" fill="%s" stroke="var(--surface)" stroke-width="%.1f" paint-order="stroke">%s</text>'
                 % (tx, y - 9 * sc, 14 * sc, anc, HL_, 3 * sc, nm(c)))
    return ("fig", "\n".join(g), "%.1f %.1f %.1f %.1f" % (x0, y0, x1 - x0, y1 - y0), cap)


