def _gap_fig():
    parts = [title(u"2006–2025 年：從關鍵發現到獲獎的年數")]
    x0, bw = 50, 27
    for i, (y, d) in enumerate(GAPS):
        g = y - d
        h = g * 3.0
        x = x0 + i * bw
        col = RED if g >= 40 else (ORANGE if g >= 25 else (GREEN if g <= 12 else BLUE))
        parts.append(R(x, 205 - h, bw - 6, h, col, col, 2, 1, op=0.7))
        parts.append(T(x + (bw - 6) / 2.0, 200 - h, str(g), 9, col))
        parts.append(T(x + (bw - 6) / 2.0, 220, u"'%02d" % (y % 100), 9, MUTED))
    parts.append(P("M45 205 L600 205", LINE, sw=1))
    parts.append(T(320, 244, u"依本課程各年精讀課中的關鍵年份估算；2012、2014 年取兩位得主中較早的發現", 9.5, MUTED))
    return svg(*parts)


