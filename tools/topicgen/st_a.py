def _book_fig():
    out = [title(u"股價怎麼來:買賣雙方的撮合")]
    out.append(T(170, 50, u"委買(想買的人)", 10, GREEN))
    out.append(T(470, 50, u"委賣(想賣的人)", 10, RED))
    buys = [(u"100.0", u"30 張"), (u"99.5", u"52 張"), (u"99.0", u"88 張")]
    sells = [(u"100.5", u"41 張"), (u"101.0", u"65 張"), (u"101.5", u"97 張")]
    for i, (p, q) in enumerate(buys):
        y = 64 + i * 28
        out.append(R(90, y, 160, 22, GREEN, GREEN, 4, 1, op=0.15))
        out.append(T(130, y + 15, p, 10, TXT))
        out.append(T(210, y + 15, q, 9.5, MUTED))
    for i, (p, q) in enumerate(sells):
        y = 64 + i * 28
        out.append(R(390, y, 160, 22, RED, RED, 4, 1, op=0.15))
        out.append(T(430, y + 15, p, 10, TXT))
        out.append(T(510, y + 15, q, 9.5, MUTED))
    out.append(T(320, 92, u"最高買價 100.0", 9, MUTED))
    out.append(T(320, 108, u"最低賣價 100.5", 9, MUTED))
    out.append(T(320, 170, u"有人願意用 100.5 買,或有人願意用 100.0 賣,就「成交」,那個價格就是最新股價", 10, ACC))
