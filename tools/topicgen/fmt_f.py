# ---------- 真的產生一個 WAV ----------
_samples = [0, 12000, 24000, 12000, 0, -12000, -24000, -12000]
_buf = io.BytesIO()
_w = wave.open(_buf, "wb")
_w.setnchannels(1)
_w.setsampwidth(2)
_w.setframerate(8000)
_w.writeframes(b"".join(struct.pack("<h", s) for s in _samples))
_w.close()
WAV = _buf.getvalue()
assert WAV[0:4] == b"RIFF" and WAV[8:12] == b"WAVE" and len(WAV) == 60

