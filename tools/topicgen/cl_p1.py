def inverter(ox=0, oy=0, labels=True):
    """反相器 layout 俯視圖（寬約 300、高約 280）。"""
    X = lambda v: v + ox
    Y = lambda v: v + oy
    out = [
        lyr("nwell", X(60), Y(20), 240, 125),
        lyr("m1", X(60), Y(28), 240, 22),                 # VDD
        lyr("m1", X(60), Y(250), 240, 22),                # GND
        lyr("active", X(105), Y(70), 150, 50),            # PMOS
        lyr("active", X(105), Y(170), 150, 42),           # NMOS
        lyr("poly", X(172), Y(55), 16, 172),              # 閘極
        lyr("poly", X(150), Y(122), 50, 24),              # 閘極接點墊
        lyr("m1", X(118), Y(40), 24, 70),                 # PMOS source → VDD
        lyr("m1", X(118), Y(176), 24, 86),                # NMOS source → GND
        lyr("m1", X(214), Y(80), 24, 126),                # 汲極相連 = 輸出
        lyr("m1", X(214), Y(150), 86, 16),                # 輸出往右拉
        lyr("m1", X(60), Y(126), 104, 16),                # 輸入從左邊進來
    ]
    for cx, cy in ((125, 88), (221, 88), (125, 186), (221, 186), (170, 129)):
        out.append(lyr("contact", X(cx), Y(cy), 10, 10))
    if labels:
        out += [T(X(180), Y(44), "VDD", 10, TXT), T(X(180), Y(266), "GND", 10, TXT),
                T(X(66), Y(120), u"輸入 A", 9, BLUE, "start"), T(X(296), Y(180), u"輸出 Y", 9, BLUE, "end"),
                T(X(265), Y(100), "PMOS", 9, GREEN, "start"), T(X(265), Y(196), "NMOS", 9, GREEN, "start")]
    return "".join(out)


