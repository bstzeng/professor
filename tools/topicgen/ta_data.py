def all_cards():
    """回傳 78 張牌：(id, 名稱, 類別, 正位, 逆位, 附註)。"""
    out = []
    for n, name, en, up, rev, astro in MAJORS:
        out.append((u"M%d" % n, name, u"大阿爾克那", up, rev, u"%s・%s" % (en, astro)))
    for s in SUIT_ORDER:
        for i, (up, rev) in enumerate(MINORS[s]):
            out.append((u"%s%d" % (s, i + 1), s + RANKS[i], s, up, rev, u""))
    return out


assert len(all_cards()) == 78
assert all(len(MINORS[s]) == 14 for s in SUIT_ORDER)
