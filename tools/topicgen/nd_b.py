def _yield_fig():
    out = [title(u"殖利率與價格:翹翹板的兩端(反向關係)")]
    # seesaw: price up -> yield down
    out.append(P("M120 130 L520 130", MUTED, sw=2))
    out.append(P("M320 130 L320 170", MUTED, sw=2))
    out.append(P("M300 170 L340 170 L320 130 Z", MUTED, "var(--surface)", 1))
    # left up (price), right down (yield)
    out.append(box(70, 70, 130, 44, u"價格", u"↑ 上漲", GREEN))
    out.append(box(440, 146, 130, 44, u"殖利率", u"↓ 下降", RED))
