def _compass(order_dirs, cx, cy, r, label):
    import math
    pos = {u"南": -90, u"西南": -45, u"西": 0, u"西北": 45, u"北": 90, u"東北": 135, u"東": 180, u"東南": -135}
    out = [C(cx, cy, r + 26, LINE, "var(--surface)"), T(cx, cy + 4, label, 10, ACC)]
    for k, d in order_dirs:
        a = math.radians(pos[d])
        x = cx + r * math.cos(a)
        y = cy + r * math.sin(a)
        out.append(T(x, y + 4, k, 11, TXT))
        out.append(T(cx + (r + 40) * math.cos(a), cy + (r + 40) * math.sin(a) + 3, d, 8, MUTED))
    return "".join(out)


