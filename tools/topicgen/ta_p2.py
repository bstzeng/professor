def major_row(nums, heading):
    out = [title(heading)]
    n = len(nums)
    w = 90 if n <= 5 else 80
    gap = min(40.0, (600 - n * w) / float(max(n - 1, 1))) if n > 1 else 0
    x0 = (640 - (n * w + (n - 1) * gap)) / 2.0
    for i, k in enumerate(nums):
        x = x0 + i * (w + gap)
        out.append(card(x, 40, MAJORS[k][1], u"%d" % k, w, 140, GOLD, sub=ROMAN[k]))
    return svg(*out)


def major_table(nums):
    rows = []
    for k in nums:
        n, name, en, up, rev, astro = MAJORS[k]
        rows.append([u"%d %s<br><span style=\"color:var(--text-muted);font-size:0.85em\">%s</span>" % (n, name, en),
                     MAJOR_IMAGE[k], up, rev])
    return ("t", [u"牌", u"牌面（偉特-史密斯）", u"正位", u"逆位"], rows)


def _journey():
    import math
    out = [title(u"愚人之旅：0 號愚人走過 21 張牌")]
    cx, cy, r = 320, 150, 110
    out.append(C(cx, cy, r, LINE, "none"))
    for k in range(1, 22):
        a = -math.pi / 2 + (k - 1) * 2 * math.pi / 21
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        col = [ACC, PURPLE, GREEN][(k - 1) // 7]
        out.append(C(x, y, 13, col, "var(--surface)"))
        out.append(T(x, y + 4, u"%d" % k, 9, col))
    out.append(C(cx, cy, 26, GOLD, "var(--gold-soft)"))
    out.append(T(cx, cy - 2, u"0", 12, GOLD)); out.append(T(cx, cy + 13, u"愚人", 9, GOLD))
    out.append(T(560, 80, u"1～7", 10.5, ACC)); out.append(T(560, 96, u"外在世界：學習規則", 9, MUTED))
    out.append(T(560, 140, u"8～14", 10.5, PURPLE)); out.append(T(560, 156, u"內在世界：認識自己", 9, MUTED))
    out.append(T(560, 200, u"15～21", 10.5, GREEN)); out.append(T(560, 216, u"靈性世界：突破與完成", 9, MUTED))
    out.append(T(80, 150, u"常見的", 9, MUTED)); out.append(T(80, 166, u"三組七張", 9, MUTED)); out.append(T(80, 182, u"解讀", 9, MUTED))
    return svg(*out)


_JOURNEY = _journey()


