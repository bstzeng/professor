def _income_fig():
    out = [title(u"損益表是一道減法:從營收一路扣到淨利(示意數字)")]
    base, k = 180, 1.2
    items = [(u"營收", 0, 100, BLUE), (u"營業成本", 40, 100, RED), (u"毛利", 0, 40, GREEN),
             (u"營業費用", 15, 40, RED), (u"營業利益", 0, 15, GREEN), (u"業外與稅", 12, 15, RED),
             (u"稅後淨利", 0, 12, GREEN)]
    for i, (lab, lo, hi, col) in enumerate(items):
        x = 40 + i * 80 + 16
        top, bot = base - hi * k, base - lo * k
        out.append(R(x, top, 48, bot - top, col, col, 3, 1, op=0.7))
        v = hi - lo
        out.append(T(x + 24, top - 5, (u"-%d" % v) if col == RED else (u"%d" % v), 9.5, col))
        out.append(T(x + 24, base + 16, lab, 9, MUTED))
    out.append(P("M40 %g H600" % base, MUTED, sw=1.2))
    out.append(T(320, 222, u"毛利率 40%、營業利益率 15%、淨利率 12%:每往下一層,就知道錢被哪裡吃掉", 10, ACC))
    return svg(out), 238


