def _plate():
    cx, cy, r = 170, 128, 92
    out = [C(cx, cy, r + 8, LINE, "var(--surface)")]
    out.append(P("M%d %d L%d %d A%d %d 0 0 1 %d %d Z" % (cx, cy, cx, cy - r, r, r, cx, cy + r), GREEN, GREEN, op=0.22))
    out.append(P("M%d %d L%d %d A%d %d 0 0 1 %d %d Z" % (cx, cy, cx, cy + r, r, r, cx - r, cy), GOLD, GOLD, op=0.25))
    out.append(P("M%d %d L%d %d A%d %d 0 0 1 %d %d Z" % (cx, cy, cx - r, cy, r, r, cx, cy - r), RED, RED, op=0.2))
    out.append(T(cx + 46, cy + 4, u"蔬菜 + 水果", 11, GREEN))
    out.append(T(cx + 46, cy + 20, u"半盤", 9.5))
    out.append(T(cx - 46, cy + 46, u"全穀雜糧", 11, GOLD))
    out.append(T(cx - 46, cy + 62, u"四分之一", 9.5))
    out.append(T(cx - 46, cy - 40, u"豆魚蛋肉", 11, RED))
    out.append(T(cx - 46, cy - 24, u"四分之一", 9.5))
    return out


