# ---------- 真的產生一個 ZIP ----------
_zbuf = io.BytesIO()
_z = zipfile.ZipFile(_zbuf, "w", zipfile.ZIP_DEFLATED)
_z.writestr("hi.txt", b"Hello ZIP! " * 4)
_z.close()
ZIP = _zbuf.getvalue()
_lc = ZIP.find(b"PK\x03\x04")
_cd = ZIP.find(b"PK\x01\x02")
_eo = ZIP.find(b"PK\x05\x06")
_ZIP_REG = [
    (_lc, _lc + 4, GOLD, u"PK\\x03\\x04：本地檔頭（每個檔案前）"),
    (_lc + 4, _cd, BLUE, u"檔名 hi.txt ＋ 壓縮後的內容"),
    (_cd, _cd + 4, GREEN, u"PK\\x01\\x02：中央目錄（檔案清單）"),
    (_eo, _eo + 4, RED, u"PK\\x05\\x06：目錄結束（從檔尾往前找）"),
]
assert _lc == 0 and _cd > 0 and _eo > _cd

