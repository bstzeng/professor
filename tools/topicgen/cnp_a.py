def _labels():
    out = []
    for c in ORDER:
        if c in ("HK", "MO"):
            continue
        x, y = centroid(PATHS[c])
        if c == "BJ":
            y -= 3
        if c == "TJ":
            x += 9
        out.append((BASIC[c][1][0] if c != "NM" else u"蒙", x, y + 4))
    return out


