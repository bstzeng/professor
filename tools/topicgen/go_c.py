# ---------------- 第 14 課：斷點 ----------------
CUT_B, CUT_W = "dd ee", "ed dc fe"
_c = Board(9, CUT_B, CUT_W)
_c.play(P("de"), "w")
assert _c.libs(P("dd")) == 1 and _c.libs(P("ee")) == 1 and _c.libs(P("de")) >= 2

# ---------------- 眼形 ----------------
E = {
    "str3": "di ei fi", "bent3": "ah ai bi", "str4": "ci di ei fi", "bent4": "dh di ei fi", "sq4": "dh eh di ei",
    "bulky5": "dh eh di ei fi", "flower5": "eg dh eh fh ei", "rabbit6": "eg dh eh fh ei fi", "two": "ai ci",
}
S = {k: enclose(9, v) for k, v in E.items()}


def T(k):
    return S[k][0].split()[0]


# 活棋形：白先也殺不掉
for k in ("str4", "bent4", "two"):
    b, w = S[k]
    assert not can_kill(Board(9, b, w), PTS(E[k]), P(T(k)), "w", 30), k
# 死棋形：黑先也活不了
b, w = S["sq4"]
for m in PTS(E["sq4"]) + [None]:
    b2 = Board(9, b, w)
    if m is not None:
        try:
            b2.play(m, "b")
        except Illegal:
            continue
    assert can_kill(b2, PTS(E["sq4"]), P(T("sq4")), "w", 30)

# 雙活
SEKI_B = "ah ai bh bg cg dg dh eh ei"
SEKI_W = "ch ci ag af bf cf df ef eg fg fh fi"
_r = PTS("bi di")
assert not can_kill(Board(9, SEKI_B, SEKI_W), _r, P("ah"), "w", 10)
assert not can_kill(Board(9, SEKI_B, SEKI_W), _r, P("ch"), "b", 10)

# 對殺
SEM_B = "cf df ef bg fg bh fh bi ci di ei fi"
SEM_W = "cg dg eg bf ff be fe bd cd dd ed fd"
_r = PTS("ce de ee ch dh eh")
assert can_kill(Board(9, SEM_B, SEM_W), _r, P("cg"), "b", 14)
assert can_kill(Board(9, SEM_B, SEM_W), _r, P("cf"), "w", 14)


def _sem_problem():
    bd = Board(9, SEM_B, SEM_W)
    good = []
    for m in _r:
        b2 = bd.copy()
        b2.play(m, "b")
        if can_kill(b2, _r, P("cg"), "w", 14):
            good.append(_s(m))
    assert sorted(good) == ["ch", "dh", "eh"], good
    ok = {g: ("", u"從外面緊白棋的氣。黑三口氣、白三口氣，黑先動手就快一氣，對殺勝。") for g in good}
    ng = {}
    for m in ("ce", "de", "ee"):
        ng[m] = ("ch", u"這是在填自己的氣！黑少了一口氣，白反而快一氣，對殺失敗。")
    return problem(9, SEM_B, SEM_W, "b", ok, ng, view="ab gi", prompt=u"<b>練習：</b>黑先，中間的黑三子和白三子對殺。黑該下在哪裡？",
                   other=u"這一手不在雙方的氣上，對殺不會因此變快。")


