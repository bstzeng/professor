def _seg_table(a, b):
    rows = []
    for s in SEGMENTS:
        if s[0] >= a and s[1] <= b:
            txt = u"".join(u"%s(%d)" % (LINES[k - 1], k) for k in range(s[0], s[1] + 1))
            rows.append([u"%d–%d" % (s[0], s[1]) if s[1] != s[0] else u"%d" % s[0], txt, s[3]])
    return ("t", [u"句", u"經文(括號為句號)", u"大意(概略)"], rows)


