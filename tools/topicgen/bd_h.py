def _parts_fig():
    out = [title(u"八十四句的五個大段")]
    x0, w = 40, 560
    cols = [BLUE, GRAY, PURPLE, GREEN, GOLD]
    for i, (a, b, name, _) in enumerate(PARTS):
        xa = x0 + (a - 1) * w / 84.0
        xb = x0 + b * w / 84.0
        out.append(R(xa, 60, xb - xa, 44, cols[i], cols[i], 3, 1, op=0.3))
        if b - a >= 6:
            out.append(T((xa + xb) / 2, 86, name if b - a > 12 else u"結尾", 10, TXT))
        if a != 18:
            out.append(T(xa, 122, u"%d" % a, 8.5, MUTED, "start"))
    out.append(T(x0 + w, 122, u"84", 8.5, MUTED, "end"))
    out.append(T(x0 + 17 * w / 84.0 + 3, 50, u"↓ 第 18 句「怛姪他」:即說咒曰", 9, MUTED, "start"))
    out.append(T(320, 160, u"前段歸敬、宣告;中段讚頌、祈請;後段連續以「娑婆訶」致敬;最後再歸敬並祈願成就", 9.5, ACC))
