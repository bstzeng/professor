    out = [title(u"波茲曼因子：能量越高，越不可能")]
    for kt, c in ((0.5, BLUE), (1.0, ORANGE), (2.0, RED)):
        pts = "".join("%s%.1f %.1f" % ("L" if i else "M", sx(i * 0.05), 190 - 140 * math.exp(-i * 0.05 / kt)) for i in range(101))
        out.append(P(pts, c, sw=2))
