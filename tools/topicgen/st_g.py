def _dca_fig():
    prices = [100, 80, 60, 80, 100, 120]
    out = [title(u"定期定額:每月固定投入 12,000 元(示意)")]
    x0, base = 90, 176
    for i, p in enumerate(prices):
        x = x0 + i * 82
        h = p * 1.0
        units = 12000 // p
        out.append(R(x, base - h, 40, h, BLUE, BLUE, 3, 1, op=0.55))
        out.append(T(x + 20, base - h - 5, u"%d 元" % p, 9, BLUE))
        out.append(T(x + 20, base + 15, u"第 %d 月" % (i + 1), 8.5, MUTED))
        out.append(T(x + 20, base + 29, u"買 %d 股" % units, 9, GREEN))
    out.append(P("M70 %g H590" % base, MUTED, sw=1.2))
    out.append(T(320, 230, u"共投入 72,000 元、買到 840 股:平均成本約 85.7 元,低於這六個月的平均股價 90 元", 10, ACC))
    out.append(T(320, 252, u"價格低時自動買比較多、價格高時買比較少——不必判斷時機", 9.5))
    return svg(out), 268


