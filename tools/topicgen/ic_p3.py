def fullname(n):
    name, up, lo, _ = HEX[n - 1]
    if up == lo:
        return u"%s為%s" % (name, TRIGRAMS[up][2])
    return TRIGRAMS[up][2] + TRIGRAMS[lo][2] + name


def change(n, moving):
    """第 n 卦在 moving（1～6）位置變爻後的卦序。"""
    ls = list(hex_lines(n))
    for m in moving:
        ls[m - 1] = "0" if ls[m - 1] == "1" else "1"
    return LINES_TO_NUM["".join(ls)]


def hu(n):
    ls = hex_lines(n)
    return LINES_TO_NUM[ls[1:4] + ls[2:5]]


def cuo(n):
    return LINES_TO_NUM["".join("0" if c == "1" else "1" for c in hex_lines(n))]


def zong(n):
    return LINES_TO_NUM[hex_lines(n)[::-1]]


def HN(n):
    return u"第 %d 卦%s" % (n, fullname(n))


