def _div_fig():
    import math
    out = [title(u"分散:持股數增加,風險先快速下降,再趨於平緩(示意)")]
    x0, y0, w, h = 80, 44, 500, 140
    out.append(P("M%g %g V%g H%g" % (x0, y0, y0 + h, x0 + w), MUTED, sw=1.2))
    pts = []
    for n in range(1, 41):
        risk = 0.35 + 0.65 / math.sqrt(n)
        pts.append("%.1f %.1f" % (x0 + (n - 1) / 39.0 * w, y0 + h - risk * h * 0.95))
    out.append(P("M" + " L".join(pts), ACC, sw=2.2))
    fl = y0 + h - 0.35 * h * 0.95
    out.append(P("M%g %g H%g" % (x0, fl, x0 + w), RED, sw=1.2, dash="4 3"))
    out.append(T(x0 + w - 4, fl + 14, u"市場風險(系統性風險):分散也消除不了", 9, RED, "end"))
    out.append(T(x0 + 150, y0 + 40, u"個別公司風險:可以靠分散降低", 9, ACC, "start"))
    for n, lab in ((1, u"1 支"), (10, u"10 支"), (20, u"20 支"), (40, u"40 支")):
        out.append(T(x0 + (n - 1) / 39.0 * w, y0 + h + 14, lab, 8.5))
    out.append(T(320, 222, u"分散能消掉「單一公司出事」的風險,但消不掉「整個市場下跌」的風險", 10, ACC))
    return svg(out), 238


