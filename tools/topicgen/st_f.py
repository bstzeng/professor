def _compound_fig():
    out = [title(u"每月投入 5000 元、年化 6%,持續到 65 歲(示意)")]
    rows = []
    for start in (25, 35, 45):
        n = (65 - start) * 12
        rm = 1.06 ** (1 / 12.0) - 1
        fv = 5000 * ((1 + rm) ** n - 1) / rm / 10000.0
        rows.append((start, n * 5000 / 10000.0, fv))
    vmax = 1050.0
    for i, (start, prin, fv) in enumerate(rows):
        y = 52 + i * 46
        out.append(T(100, y + 18, u"%d 歲開始" % start, 10, TXT, "end"))
        wf = 370 * fv / vmax
        wp = 370 * prin / vmax
        out.append(R(110, y, wf, 28, GREEN, GREEN, 3, 1, op=0.35))
        out.append(R(110, y, wp, 28, BLUE, BLUE, 3, 1, op=0.75))
        out.append(T(110 + wf + 6, y + 18, u"約 %d 萬(本金 %d 萬)" % (round(fv), round(prin)), 9.5, GREEN, "start"))
    out.append(T(320, 212, u"早 10 年開始,本金只多三分之一,最後的金額卻多了一倍左右——多出來的主要是「時間」", 10, ACC))
