# ---------- 真的產生一個 2×2 的 BMP ----------
_W = _H = 2
_ROWSIZE = (_W * 3 + 3) & ~3
# 由上到下：紅、綠 / 藍、白（螢幕上）；BMP 由下往上、用 BGR
_TOP = [bytes([0, 0, 255, 255, 0, 0]),      # 螢幕上第一列：紅、綠 → 存成 BGR
        bytes([255, 0, 0, 0, 255, 0])]
_ROWS_BOTTOM_UP = [bytes([255, 0, 0, 255, 255, 255]),   # 底列：藍、白（BGR）
                   bytes([0, 0, 255, 0, 255, 0])]       # 頂列：紅、綠（BGR）
_PIX = b"".join(r + b"\x00" * (_ROWSIZE - len(r)) for r in _ROWS_BOTTOM_UP)
_DIB = struct.pack("<IiiHHIIiiII", 40, _W, _H, 1, 24, 0, len(_PIX), 2835, 2835, 0, 0)
BMP = b"BM" + struct.pack("<IHHI", 14 + 40 + len(_PIX), 0, 0, 54) + _DIB + _PIX
assert len(BMP) == 70

