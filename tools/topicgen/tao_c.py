def _taiji_fig():
    out = [title(u"陰陽、太極、五行、八卦")]
    cx, cy, r = 120, 132, 62
    out.append(C(cx, cy, r, TXT, "var(--surface)", sw=1.6))
    out.append(P("M%g %g A%g %g 0 0 0 %g %g A%g %g 0 0 0 %g %g A%g %g 0 0 1 %g %g Z" % (
        cx, cy - r, r, r, cx, cy + r, r / 2.0, r / 2.0, cx, cy, r / 2.0, r / 2.0, cx, cy - r), TXT, TXT, sw=0))
    out.append(C(cx, cy - r / 2.0, 8, TXT, TXT, sw=0))
    out.append(C(cx, cy + r / 2.0, 8, TXT, "var(--surface)", sw=0))
    out.append(T(cx, cy + r + 20, u"太極圖:陰中有陽,陽中有陰", 9, MUTED))
    import math
    names = [(u"木", GREEN), (u"火", RED), (u"土", GOLD), (u"金", GRAY), (u"水", BLUE)]
    ox, oy, rr = 380, 132, 62
    pts = []
    for i, (n, c) in enumerate(names):
        a = -math.pi / 2 + i * 2 * math.pi / 5
        x, y = ox + rr * math.cos(a), oy + rr * math.sin(a)
        pts.append((x, y))
        out.append(C(x, y, 17, c, "var(--surface)"))
        out.append(T(x, y + 5, n, 12, c))
    for i in range(5):
        (x1, y1), (x2, y2) = pts[i], pts[(i + 1) % 5]
        dx, dy = x2 - x1, y2 - y1
        d = math.hypot(dx, dy)
        out.append(A(x1 + dx * 19 / d, y1 + dy * 19 / d, x2 - dx * 21 / d, y2 - dy * 21 / d, LINE, sw=1.2, head=5))
    out.append(T(ox, oy + rr + 30, u"箭頭:相生(木生火、火生土……)", 9, MUTED))
    out.append(T(560, 76, u"八卦", 11, ACC))
    for i, (g, n) in enumerate([(u"☰", u"乾・天"), (u"☷", u"坤・地"), (u"☵", u"坎・水"), (u"☲", u"離・火")]):
        out.append(T(546, 104 + i * 24, g, 16, TXT))
        out.append(T(566, 102 + i * 24, n, 9.5, MUTED, "start"))
    out.append(T(560, 206, u"(另有震、巽、艮、兌)", 8.5, MUTED))
