def gone(*pts):
    return lambda bd: all(P(p) not in bd.g for p in pts)


def expect_winners(n, b, w, target, to_move, answers, depth=7, region=None):
    got = sorted(tac_winners(n, b, w, target, to_move, depth, PTS(region) if region else None))
    assert got == sorted(answers.split()), ("winners mismatch", target, got, answers)


