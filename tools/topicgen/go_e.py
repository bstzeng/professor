# 金角銀邊草肚皮：圍 9 個點需要的子數
CORNER = "da db dc ad bd cd"
SIDE = "hb ha hc lb la lc id jd kd"
CENTER = "ij jj kj hk hl hm lk ll lm in jn kn"
assert len(PTS(CORNER)) == 6 and len(PTS(SIDE)) == 9 and len(PTS(CENTER)) == 12


def _enclosed(stones, cells):
    bd = Board(19, stones)
    seen, st = set(PTS(cells)[:1]), PTS(cells)[:1]
    while st:
        q = st.pop()
        for r in bd.nb(q):
            if r not in bd.g and r not in seen:
                seen.add(r)
                st.append(r)
    return len(seen)


assert _enclosed(CORNER, "aa") == 9
assert _enclosed(SIDE, "ia") == 9
assert _enclosed(CENTER, "ik") == 9

