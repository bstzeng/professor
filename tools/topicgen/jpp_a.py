def _labels(skip=("13", "27", "37", "14", "11", "41", "25", "29", "26", "28", "24", "30")):
    out = []
    for c in ORDER:
        if c in skip:
            continue
        x, y = centroid(JP_PATHS[c])
        out.append((short(c)[:2], x, y + 4))
    return out


