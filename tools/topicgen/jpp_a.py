def _kuni_rows():
    return [[LS(LESSON[c], nm(c)), BASIC[c][8], DATA[c]["origin"]] for c in ORDER]


def _food_rows():
    return [[LS(LESSON[c], nm(c)), REGIONS[BASIC[c][3]][0], u"、".join(f[0] for f in DATA[c]["food"][:3]), DATA[c].get("omiyage", u"")] for c in ORDER]


def _wh_rows():
    seen, rows = [], []
    for c in ORDER:
        for w in DATA[c]["wh"]:
            key = w.split(u"（")[0].split(u"：清水寺")[0]
            if key in seen or (c == "25" and key.startswith(u"古都京都")):     # 古都京都的項目放在京都那一列
                continue
            seen.append(key)
            rows.append([key, LS(LESSON[c], nm(c))])
    return rows


