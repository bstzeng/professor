def suit_grid(s):
    col = SUITS[s][1]
    out = [title(u"%s的 14 張牌（%s元素）" % (s, SUITS[s][0]))]
    for i in range(14):
        x = 14 + (i % 7) * 88
        y = 36 + (i // 7) * 118
        name = RANKS[i]
        if i < 10:
            out.append(card(x, y, name, u"", 74, 108, col, suit=s))
        else:
            out.append(card(x, y, name, u"", 74, 108, col, sub=[u"侍", u"騎", u"后", u"王"][i - 10]))
    return svg(*out)


def suit_table(s):
    rows = []
    for i, (up, rev) in enumerate(MINORS[s]):
        rows.append([s + RANKS[i], up, rev])
    return ("t", [u"牌", u"正位", u"逆位"], rows)


