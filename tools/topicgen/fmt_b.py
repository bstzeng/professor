def _huff(text):
    freq = {}
    for c in text:
        freq[c] = freq.get(c, 0) + 1
    heap = [[w, i, c] for i, (c, w) in enumerate(sorted(freq.items()))]
    heapq.heapify(heap)
    nid = len(heap)
    while len(heap) > 1:
        a = heapq.heappop(heap)
        b = heapq.heappop(heap)
        heapq.heappush(heap, [a[0] + b[0], nid, [a, b]])
        nid += 1
    codes = {}

    def walk(node, pre=""):
        if isinstance(node[2], str):
            codes[node[2]] = pre or "0"
        else:
            walk(node[2][0], pre + "0")
            walk(node[2][1], pre + "1")
    walk(heap[0])
    return freq, codes


