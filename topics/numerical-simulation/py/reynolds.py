# 第 19 課：幾個情境的雷諾數 Re = U L / ν
cases = [
    # 名稱,               速度 m/s, 長度 m,  運動黏度 m²/s
    ("自來水管",           1.0,     0.02,   1.0e-6),
    ("游泳池水面漂流",     0.05,    2.0,    1.0e-6),
    ("室內空氣對流",       0.2,     3.0,    1.5e-5),
    ("蝕刻腔 20 mTorr Ar", 2.0,     0.3,    0.52),
    ("咖啡攪拌",           0.1,     0.04,   1.0e-6),
]
for name, U, L, nu in cases:
    Re = U * L / nu
    kind = "層流" if Re < 2000 else "可能紊流"
    print(f"{name:16s} Re = {Re:10.3g}  {kind}")

# 蝕刻腔的運動黏度怎麼來：ν = μ/ρ，ρ = pM/(RT)
p, M, R, T, mu = 20 * 0.13332, 0.040, 8.314, 300.0, 2.27e-5
rho = p * M / (R * T)
print(f"20 mTorr 氬氣：ρ = {rho:.2e} kg/m³，ν = μ/ρ = {mu / rho:.2f} m²/s")
